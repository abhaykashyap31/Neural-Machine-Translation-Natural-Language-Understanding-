class LSTMEncoder(nn.Module):
    def __init__(self, vocab_size, embedding_dim, hidden_dim, num_layers=2, dropout=0.2):
        super(LSTMEncoder, self).__init__()
        self.embedding = nn.Embedding(vocab_size, embedding_dim)
        self.rnn = nn.LSTM(embedding_dim, hidden_dim, num_layers,
                            batch_first=True, dropout=dropout, bidirectional=True)
        self.fc = nn.Linear(hidden_dim * 2, hidden_dim)

    def forward(self, x):
        embedded = self.embedding(x)
        outputs, (hidden, cell) = self.rnn(embedded)
        hidden = torch.cat((hidden[-2,:,:], hidden[-1,:,:]), dim=1)
        cell = torch.cat((cell[-2,:,:], cell[-1,:,:]), dim=1)
        hidden = self.fc(hidden).unsqueeze(0)
        cell = self.fc(cell).unsqueeze(0)
        return outputs, (hidden, cell)

class LSTMDecoder(nn.Module):
    def __init__(self, vocab_size, embedding_dim, hidden_dim, num_layers=2, dropout=0.2):
        super(LSTMDecoder, self).__init__()
        self.embedding = nn.Embedding(vocab_size, embedding_dim)
        self.rnn = nn.LSTM(embedding_dim, hidden_dim, num_layers,
                            batch_first=True, dropout=dropout)
        self.fc_out = nn.Linear(hidden_dim, vocab_size)
        self.dropout = nn.Dropout(dropout)

    def forward(self, x, hidden):
        x = x.unsqueeze(1)
        embedded = self.dropout(self.embedding(x))
        output, (hidden, cell) = self.rnn(embedded, hidden)
        prediction = self.fc_out(output.squeeze(1))
        return prediction, (hidden, cell)

class LSTMSeq2SeqModel(nn.Module):
    def __init__(self, encoder, decoder):
        super(LSTMSeq2SeqModel, self).__init__()
        self.encoder = encoder
        self.decoder = decoder

    def forward(self, src, trg):
        _, (hidden, cell) = self.encoder(src)
        num_layers = self.decoder.rnn.num_layers
        hidden = hidden.repeat(num_layers, 1, 1)
        cell = cell.repeat(num_layers, 1, 1)
        outputs = torch.zeros(trg.shape[0], trg.shape[1], self.decoder.fc_out.out_features).to(trg.device)
        decoder_input = trg[:, 0]
        for t in range(1, trg.shape[1]):
            decoder_output, (hidden, cell) = self.decoder(decoder_input, (hidden, cell))
            outputs[:, t, :] = decoder_output
            decoder_input = trg[:, t]
        return outputs

