def train_hybrid_model(model, train_loader, criterion, optimizer, device):
    model.train()
    total_loss = 0

    for batch in train_loader:
        src = batch['english'].to(device)
        trg = batch['hindi'].to(device)

        # Use teacher forcing: decoder input is trg[:-1], target is trg[1:]
        trg_input = trg[:, :-1]
        trg_target = trg[:, 1:]

        # Create padding masks
        src_padding_mask = (src == 0)
        trg_padding_mask = (trg_input == 0)

        optimizer.zero_grad()

        outputs = model(
            src,
            trg_input,
            src_key_padding_mask=src_padding_mask,
            tgt_key_padding_mask=trg_padding_mask
        )

        # Reshape for loss calculation
        outputs = outputs.reshape(-1, outputs.shape[-1])
        trg_target = trg_target.reshape(-1)

        loss = criterion(outputs, trg_target)
        loss.backward()

        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1)
        optimizer.step()
        total_loss += loss.item()

    return total_loss / len(train_loader)

def evaluate_hybrid_model(model, test_loader, device, hindi_vocab):
    model.eval()
    references = []
    hypotheses = []

    with torch.no_grad():
        for batch in test_loader:
            src = batch['english'].to(device)
            trg = batch['hindi'].to(device)

            # Generate translations
            max_len = trg.shape[1] - 1
            batch_size = src.size(0)
            predicted_tokens = torch.ones(batch_size, 1).fill_(hindi_vocab['<sos>']).long().to(device)

            for _ in range(max_len):
                # Create padding mask
                src_padding_mask = (src == 0)
                tgt_padding_mask = (predicted_tokens == 0)

                # Get next token predictions
                output = model(
                    src,
                    predicted_tokens,
                    src_key_padding_mask=src_padding_mask,
                    tgt_key_padding_mask=tgt_padding_mask
                )

                # Select token with highest probability
                next_token = output[:, -1, :].argmax(1).unsqueeze(1)
                predicted_tokens = torch.cat([predicted_tokens, next_token], dim=1)

                # Stop if all sequences have predicted EOS
                if (next_token.squeeze(1) == hindi_vocab['<eos>']).all():
                    break

            # Format references and hypotheses for BLEU calculation
            for i in range(src.shape[0]):
                ref_tokens = [hindi_vocab.get(idx.item(), '<unk>') for idx in trg[i, 1:] if idx.item() != 0]
                hyp_tokens = [hindi_vocab.get(idx.item(), '<unk>') for idx in predicted_tokens[i, 1:] if idx.item() not in [0, hindi_vocab['<eos>']]]
                references.append([ref_tokens])  # Each reference is a list of tokens
                hypotheses.append(hyp_tokens)

    # Calculate BLEU score
    bleu = corpus_bleu(references, hypotheses)
    return bleu

def display_hybrid_translations(model, test_loader, device, hindi_vocab, reverse_hindi_vocab, reverse_english_vocab, num_samples=5):
    model.eval()
    samples = []

    with torch.no_grad():
        for batch in test_loader:
            src = batch['english'].to(device)
            trg = batch['hindi'].to(device)

            # Generate translations
            max_len = 50  # Maximum length limit
            batch_size = src.size(0)
            predicted_tokens = torch.ones(batch_size, 1).fill_(hindi_vocab['<sos>']).long().to(device)

            for _ in range(max_len):
                # Create padding mask
                src_padding_mask = (src == 0)
                tgt_padding_mask = (predicted_tokens == 0)

                # Get next token predictions
                output = model(
                    src,
                    predicted_tokens,
                    src_key_padding_mask=src_padding_mask,
                    tgt_key_padding_mask=tgt_padding_mask
                )

                # Select token with highest probability
                next_token = output[:, -1, :].argmax(1).unsqueeze(1)
                predicted_tokens = torch.cat([predicted_tokens, next_token], dim=1)

                # Stop if all sequences have predicted EOS
                if (next_token.squeeze(1) == hindi_vocab['<eos>']).all():
                    break

            # Get a few examples
            for i in range(min(num_samples, src.size(0))):
                # Source sentence (English)
                src_tokens = [reverse_english_vocab.get(idx.item(), '<unk>') for idx in src[i] if idx.item() != 0]

                # Reference translation (Hindi)
                ref_tokens = [reverse_hindi_vocab.get(idx.item(), '<unk>') for idx in trg[i] if idx.item() not in [0, hindi_vocab['<sos>'], hindi_vocab['<eos>']]]

