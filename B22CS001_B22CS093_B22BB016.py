class PositionalEncoding(nn.Module):
    def __init__(self, d_model, max_len=5000):
        super(PositionalEncoding, self).__init__()
        pe = torch.zeros(max_len, d_model)
        position = torch.arange(0, max_len, dtype=torch.float).unsqueeze(1)
        div_term = torch.exp(torch.arange(0, d_model, 2).float() * (-torch.log(torch.tensor(10000.0)) / d_model))
        pe[:, 0::2] = torch.sin(position * div_term)
        pe[:, 1::2] = torch.cos(position * div_term)
        pe = pe.unsqueeze(0)
        self.register_buffer('pe', pe)

    def forward(self, x):
        return x + self.pe[:, :x.size(1)]

class TransformerModel(nn.Module):
    def __init__(self, src_vocab_size, tgt_vocab_size, d_model=512, nhead=8,
                 num_encoder_layers=6, num_decoder_layers=6, dim_feedforward=2048, dropout=0.1):
        super(TransformerModel, self).__init__()
        self.src_embedding = nn.Embedding(src_vocab_size, d_model)
        self.tgt_embedding = nn.Embedding(tgt_vocab_size, d_model)
        self.positional_encoding = PositionalEncoding(d_model)

        # Set batch_first=True to match our data format
        self.transformer = nn.Transformer(
            d_model=d_model,
            nhead=nhead,
            num_encoder_layers=num_encoder_layers,
            num_decoder_layers=num_decoder_layers,
            dim_feedforward=dim_feedforward,
            dropout=dropout,
            batch_first=True  # Ensure proper batch format
        )
        self.fc_out = nn.Linear(d_model, tgt_vocab_size)

    def forward(self, src, trg, src_mask=None, tgt_mask=None, memory_mask=None,
                src_key_padding_mask=None, tgt_key_padding_mask=None, memory_key_padding_mask=None):
        # Embed and add positional encoding
        src_emb = self.positional_encoding(self.src_embedding(src))
        trg_emb = self.positional_encoding(self.tgt_embedding(trg))

        # Generate target mask if not provided
        if tgt_mask is None and trg is not None:
            tgt_mask = self.transformer.generate_square_subsequent_mask(trg.size(1)).to(trg.device)

        # Transformer forward pass with corrected parameter names
        output = self.transformer(
            src_emb, trg_emb,
            src_mask=src_mask,
            tgt_mask=tgt_mask,
            memory_mask=memory_mask,
            src_key_padding_mask=src_key_padding_mask,
            tgt_key_padding_mask=tgt_key_padding_mask,
            memory_key_padding_mask=memory_key_padding_mask
        )
        return self.fc_out(output)

def create_masks(src, trg, pad_idx):
    src_mask = (src == pad_idx)
    trg_mask = (trg == pad_idx)
    return src_mask, trg_mask

def train_model(model, train_loader, criterion, optimizer, device, model_type='lstm'):
    model.train()
    total_loss = 0
    for batch in train_loader:
        src = batch['english'].to(device)
        trg = batch['hindi'].to(device)
        optimizer.zero_grad()

        if model_type == 'transformer':
            # Use teacher forcing: decoder input is trg[:-1], target is trg[1:]
            trg_input = trg[:, :-1]
            trg_target = trg[:, 1:]

            # Create padding masks
            src_padding_mask = (src == 0)
            trg_padding_mask = (trg_input == 0)

            outputs = model(
                src, trg_input,
                src_key_padding_mask=src_padding_mask,
                tgt_key_padding_mask=trg_padding_mask
            )

            # Reshape for loss calculation
            outputs = outputs.reshape(-1, outputs.shape[-1])
            trg_target = trg_target.reshape(-1)

            loss = criterion(outputs, trg_target)
        else:
            outputs = model(src, trg)
            outputs = outputs[:, 1:].reshape(-1, outputs.shape[-1])
            trg = trg[:, 1:].reshape(-1)
            loss = criterion(outputs, trg)

        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1)
        optimizer.step()
        total_loss += loss.item()
    return total_loss / len(train_loader)


