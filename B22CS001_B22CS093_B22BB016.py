class NMTDataset(Dataset):
    def __init__(self, english_file, hindi_file, max_length=50,
                 english_vocab=None, hindi_vocab=None):
        with open(english_file, 'r', encoding='utf-8') as f:
            self.english_sentences = f.readlines()
        with open(hindi_file, 'r', encoding='utf-8') as f:
            self.hindi_sentences = f.readlines()

        self.english_tokens = [['<sos>'] + sentence.strip().split()[:max_length] + ['<eos>']
                              for sentence in self.english_sentences]
        self.hindi_tokens = [['<sos>'] + sentence.strip().split()[:max_length] + ['<eos>']
                            for sentence in self.hindi_sentences]

        if english_vocab and hindi_vocab:
            self.english_vocab = english_vocab
            self.hindi_vocab = hindi_vocab
        else:
            self.english_vocab = self.create_vocabulary(self.english_tokens)
            self.hindi_vocab = self.create_vocabulary(self.hindi_tokens)

        if not english_vocab:
            self.english_embeddings = self.create_embeddings(self.english_vocab)
            self.hindi_embeddings = self.create_embeddings(self.hindi_vocab)
        else:
            self.english_embeddings = None
            self.hindi_embeddings = None

    def create_vocabulary(self, tokenized_sentences):
        vocab = {'<pad>': 0, '<sos>': 1, '<eos>': 2, '<unk>': 3}
        current_index = 4
        for sentence in tokenized_sentences:
            for token in sentence:
                if token not in vocab:
                    vocab[token] = current_index
                    current_index += 1
        return vocab

    def create_embeddings(self, vocab, embedding_dim=300):
        embeddings = torch.zeros((len(vocab), embedding_dim))
        nn.init.xavier_uniform_(embeddings)
        return embeddings

    def __len__(self):
        return len(self.english_sentences)

    def __getitem__(self, idx):
        eng_indices = [self.english_vocab.get(token, self.english_vocab['<unk>']) for token in self.english_tokens[idx]]
        hindi_indices = [self.hindi_vocab.get(token, self.hindi_vocab['<unk>']) for token in self.hindi_tokens[idx]] if idx < len(self.hindi_tokens) else []
        return {
            'english': torch.tensor(eng_indices, dtype=torch.long),
            'hindi': torch.tensor(hindi_indices, dtype=torch.long)
        }

def collate_fn(batch):
    batch.sort(key=lambda x: len(x['english']), reverse=True)
    english_sequences = [item['english'] for item in batch]
    hindi_sequences = [item['hindi'] for item in batch]
    english_padded = pad_sequence(english_sequences, batch_first=True, padding_value=0)
    hindi_padded = pad_sequence(hindi_sequences, batch_first=True, padding_value=0)
    return {'english': english_padded, 'hindi': hindi_padded}

def calculate_bleu_score(hypotheses, references):
    # Format references as a list of lists (each sublist contains references for a hypothesis)
    formatted_references = [[ref] for ref in references]  # Ensure each hypothesis has a list of references
    return corpus_bleu(formatted_references, hypotheses)

def evaluate_model(model, test_loader, device, hindi_vocab, english_vocab=None, model_type='lstm'):
    model.eval()
    references = []
    hypotheses = []
    with torch.no_grad():
        for batch in test_loader:
            src = batch['english'].to(device)
            trg = batch['hindi'].to(device)
            if model_type == 'lstm':
                _, (hidden, cell) = model.encoder(src)
                num_layers = model.decoder.rnn.num_layers
                hidden = hidden.repeat(num_layers, 1, 1)
                cell = cell.repeat(num_layers, 1, 1)
                decoder_input = torch.ones(trg.size(0), dtype=torch.long, device=device) * hindi_vocab['<sos>']
                predicted_tokens = []
                for _ in range(trg.shape[1]-1):
                    decoder_output, (hidden, cell) = model.decoder(decoder_input, (hidden, cell))
                    predicted_token = decoder_output.argmax(1)
                    predicted_tokens.append(predicted_token)
                    decoder_input = predicted_token
                predicted_tokens = torch.stack(predicted_tokens).T
            else:  # Transformer
                max_len = trg.shape[1] - 1
                batch_size = src.size(0)
                predicted_tokens = torch.ones(batch_size, 1).fill_(hindi_vocab['<sos>']).long().to(device)

                for _ in range(max_len):
                    trg_mask = model.transformer.generate_square_subsequent_mask(predicted_tokens.size(1)).to(device)
                    output = model(
                        src,
                        predicted_tokens,
                        src_key_padding_mask=(src == 0),
                        tgt_mask=trg_mask,
                        tgt_key_padding_mask=(predicted_tokens == 0)
                    )
                    next_token = output.argmax(2)[:, -1].unsqueeze(1)
                    predicted_tokens = torch.cat([predicted_tokens, next_token], dim=1)

            for i in range(src.shape[0]):
                ref_tokens = [hindi_vocab.get(idx.item(), '<unk>') for idx in trg[i, 1:] if idx.item() != 0]
